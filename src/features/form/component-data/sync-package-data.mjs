import { readdir, readFile, writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";

// Generated package files keep the renderer independently publishable while
// component folders remain the editable source of tokens and migration rules.
const root = new URL("./", import.meta.url);
const contract = new URL("../../../../packages/jb-form-builder/src/contract/", root);
const tokens = {};
const migrations = {};
const tokenMigrations = {};
for (const entry of (await readdir(root, { withFileTypes: true })).sort((a, b) => a.name.localeCompare(b.name))) {
  if (!entry.isDirectory()) continue;
  const files = await readdir(new URL(entry.name + "/", root));
  if (files.includes("theme-tokens.ts")) {
    const { componentThemeTokens } = await import(new URL(entry.name + "/theme-tokens.ts", root));
    if (componentThemeTokens.length) tokens[entry.name] = componentThemeTokens;
  }
  if (files.includes("property-migrations.ts")) {
    const { propertyMigrations } = await import(new URL(entry.name + "/property-migrations.ts", root));
    migrations[entry.name] = propertyMigrations;
  }
  if (files.includes("theme-token-migrations.ts")) {
    const { themeTokenMigrations } = await import(new URL(entry.name + "/theme-token-migrations.ts", root));
    tokenMigrations[entry.name] = themeTokenMigrations;
  }
}
const header = "// Generated by src/features/form/component-data/sync-package-data.mjs. Edit the component folders.\n";
const outputs = [
  ["component-theme-token-migrations.ts", header + "export const COMPONENT_THEME_TOKEN_MIGRATIONS = " + JSON.stringify(tokenMigrations, null, 2) + " as const;\n"],
  ["component-theme-tokens.ts", header + "export const COMPONENT_THEME_TOKENS = " + JSON.stringify(tokens, null, 2) + " as const;\n"],
  ["component-property-migrations.ts", header + "export const COMPONENT_PROPERTY_MIGRATIONS = " + JSON.stringify(migrations, null, 2) + " as const;\n"],
];
for (const [name, source] of outputs) {
  const target = new URL(name, contract);
  let current = "";
  try { current = await readFile(target, "utf8"); } catch (error) { if (error.code !== "ENOENT") throw error; }
  if (current === source) continue;
  if (process.argv.includes("--check")) throw new Error("Generated component data is stale: " + fileURLToPath(target));
  await writeFile(target, source);
}
